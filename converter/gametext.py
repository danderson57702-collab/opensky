def name_of(rtype, gid, sub, n):
    return "T_%s_%08X_%s%d" % (rtype.strip("_"), gid, sub, n)


def export(lo, strings, pack):
    """strings: dialogue.StringTables. Returns how many were written (and says which weren't found)."""
    want = {}
    for rtype, gid, sub, n, ext in KEYS:
        want.setdefault(rtype, {}).setdefault(gid, []).append((sub, n, ext))
    got = {}

    def see(p, rec, rtype):
        gid = lo.global_id(p, rec.form_id)
        fields = want[rtype].get(gid)
        if not fields:
            return
        count = {}
        for st, v in rec.subrecords():
            k = count.get(st, 0)
            count[st] = k + 1
            for sub, n, ext in fields:
                if st == sub and k == n and len(v) == 4:
                    text = strings.get(p, struct.unpack_from("<I", v)[0], ext)
                    if text and text.strip():  # (a later plugin's version of the record wins, as in the game)
                        got[name_of(rtype, gid, sub, n)] = text.strip()

    for p in lo.plugins:
        for rtype in want:
            if rtype == "CELL":  # (the places indoors: nested in the file - the load order's own list of them)
                for c in lo.interior_cells().values():
                    see(c["cell"].plugin, c["cell"], "CELL")
            elif rtype == "INFO":
                for infos in p.topic_infos().values():
                    for info in infos:
                        see(p, info, "INFO")
            else:
                for rec in p.records_of_type(rtype):
                    see(p, rec, rtype)
    names = sorted(name_of(t, g, s, n) for t, g, s, n, _e in KEYS)
    missing = [n for n in names if n not in got]
    with open(os.path.join(pack, "gametext.txt"), "w", encoding="cp1252", errors="replace", newline="\n") as f:
        for n in names:
            if n in got:
                f.write(n + "\t" + " ".join(got[n].split()) + "\n")
    print(f"game text: {len(got)} of {len(names)}" + (f"; not found: {missing}" if missing else ""))
    return len(got)


