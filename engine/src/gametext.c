// (the file's lines: <name> TAB <text>, in the names' order - as TEXTS is, so each is found from the last)
int gametext_load(const char *pack_dir) {
	char path[256];
	snprintf(path, sizeof(path), "%sgametext.txt", pack_dir);
	long size = 0;
	char *data = file_read_all(path, &size);
	if (!data)
		return 0;
	int filled = 0, at = 0;
	for (char *line = data, *end = data + size; line < end;) {
		char *eol = memchr(line, '\n', end - line);
		if (!eol)
			eol = end;
		char *tab = memchr(line, '\t', eol - line);
		if (tab) {
			const int name_len = (int)(tab - line);
			for (int k = 0; k < TEXT_COUNT; k++) {
				const int i = (at + k) % TEXT_COUNT;
				if ((int)strlen(TEXTS[i].name) == name_len && !memcmp(TEXTS[i].name, line, name_len)) {
					int n = (int)(eol - tab - 1);
					if (n > 0 && tab[n] == '\r')
						n--;
					if (n > TEXTS[i].size - 1)
						n = TEXTS[i].size - 1;
					memcpy(TEXTS[i].text, tab + 1, n);
					TEXTS[i].text[n] = 0;
					filled++, at = i + 1;
					break;
				}
			}
		}
		line = eol + 1;
	}
	free(data);
	return filled;
}

